-- Порядок полей развёртки (ffprobe field_order): "progressive" | "tt" | "bb" | "tb" | "bt".
-- Нужен для решения copy|transcode: чересстрочный H.264 проходит белый список кодеков и
-- уходит в `-c:v copy`, но MSE его либо не декодирует, либо декодирует программно — рывки
-- при копеечном битрейте. Замер: DVB-рип 720x576 tt, 3.6 Mbit/s.
ALTER TABLE media_files ADD COLUMN field_order TEXT;

-- Карты сегментов, построенные до появления признака, могли быть посчитаны в copy-профиле
-- для файла, который теперь уходит в перекодирование. Такая карта профилю не подходит.
DELETE FROM media_file_segments;
